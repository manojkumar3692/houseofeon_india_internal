import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StreamableHTTPClientTransport } from '@modelcontextprotocol/sdk/client/streamableHttp.js';
const base = process.argv[2] || 'http://127.0.0.1:3013';
const post = async (body, headers={}) => fetch(`${base}/agent/query`, { method:'POST', headers:{'Content-Type':'application/json',...headers}, body:JSON.stringify(body) });
const response = await post({tool:'search_perfumes',arguments:{occasion:'office',maxPrice:1000}});
assert.equal(response.status,200);
const rest = await response.json();
assert.ok(rest.products.length > 0);
assert.ok(rest.products.every(p=>p.pricing.price<=1000));
assert.equal((await post({tool:'track_order',arguments:{}})).status,400);
assert.equal((await post({tool:'search_perfumes',arguments:{customerPhone:'private'}})).status,400);
assert.equal((await post({tool:'search_perfumes',arguments:{}},{Origin:'https://evil.example'})).status,403);
assert.equal((await post({tool:'search_perfumes',arguments:{query:'x'.repeat(9000)}})).status,413);
const spec = await (await fetch(`${base}/agent/openapi.json`)).json();
assert.equal(spec.openapi,'3.1.0');
assert.equal(spec.paths['/agent/query'].post.requestBody.content['application/json'].schema.oneOf.length,4);
const directory = await (await fetch(`${base}/llms.txt`)).text();
assert.ok(directory.includes('/agent/mcp'));
const page = await (await fetch(`${base}/agent`)).text();
assert.ok(page.includes('Let your assistant ask House of Eon.'));
const client = new Client({name:'house-of-eon-integration-check',version:'1.0.0'});
try {
  await client.connect(new StreamableHTTPClientTransport(new URL(`${base}/agent/mcp`)));
  const list = await client.listTools();
  assert.deepEqual(list.tools.map(t=>t.name).sort(),['compare_perfumes','get_perfume','get_store_policy','search_perfumes']);
  assert.ok(list.tools.every(t=>t.annotations.readOnlyHint && !t.annotations.destructiveHint));
  const result = await client.callTool({name:'search_perfumes',arguments:{occasion:'office',maxPrice:1000}});
  assert.ok(!result.isError);
  assert.deepEqual(result.structuredContent.products.map(p=>p.id),rest.products.map(p=>p.id));
  const product = await client.callTool({name:'get_perfume',arguments:{id:'arctic-wave'}});
  assert.equal(product.structuredContent.product.pricing.price,999);
  const comparison = await client.callTool({name:'compare_perfumes',arguments:{ids:['rank','arctic-wave']}});
  assert.equal(comparison.structuredContent.products.length,2);
  const policy = await client.callTool({name:'get_store_policy',arguments:{topic:'returns'}});
  assert.ok(policy.structuredContent.sourceUrl.endsWith('/pages/return-refund-policy'));
  const invalid = await client.callTool({name:'get_perfume',arguments:{id:'missing'}});
  assert.equal(invalid.isError,true);
  const invalidArgs = await client.callTool({name:'search_perfumes',arguments:{maxPrice:-1}});
  assert.equal(invalidArgs.isError,true);
  assert.ok(!JSON.stringify([result,product,comparison,policy]).match(/orderNumber|ONLYADMIN|SUPABASE|OPENAI_API_KEY/));
} finally { await client.close(); }
console.log('Agent checks passed: official MCP client handshake, all four tools, REST parity, schema, discovery, invalid inputs, body limit, origin checks and public-only output.');
